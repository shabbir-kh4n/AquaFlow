CREATE TABLE announcements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id    BIGINT NOT NULL,
    title           VARCHAR(200) NOT NULL,
    body            TEXT NOT NULL,
    category        VARCHAR(30) NOT NULL DEFAULT 'GENERAL',
    pinned          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at      TIMESTAMP(6) WITH TIME ZONE,
    -- No ON DELETE CASCADE, same convention as support_tickets/bulk_water_purchases:
    -- SystemAdminService.deleteCommunityAdmin deletes these explicitly before the apartment.
    CONSTRAINT fk_announcements_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id),
    CONSTRAINT chk_announcements_category CHECK (
        category IN ('GENERAL', 'MAINTENANCE', 'WATER_SUPPLY', 'BILLING', 'URGENT')
    )
);

CREATE INDEX idx_announcements_apartment ON announcements (apartment_id);
