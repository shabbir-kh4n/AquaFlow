CREATE TABLE apartments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    address    VARCHAR(255),
    admin_id   BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_apartments_admin_id UNIQUE (admin_id),
    CONSTRAINT fk_apartments_admin FOREIGN KEY (admin_id) REFERENCES community_admins (id)
);

CREATE TABLE households (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id BIGINT NOT NULL,
    house_number VARCHAR(255) NOT NULL,
    floor        VARCHAR(255),
    notes        VARCHAR(255),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_households_apartment_house UNIQUE (apartment_id, house_number),
    CONSTRAINT fk_households_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id)
);

CREATE TABLE water_meters (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id BIGINT NOT NULL,
    meter_number VARCHAR(255) NOT NULL,
    household_id BIGINT,
    installed_at DATE,
    status       VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_water_meters_apartment_meter UNIQUE (apartment_id, meter_number),
    CONSTRAINT fk_water_meters_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id),
    CONSTRAINT fk_water_meters_household FOREIGN KEY (household_id) REFERENCES households (id)
);

CREATE TABLE water_usage_readings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_id      BIGINT NOT NULL,
    reading_date  DATE NOT NULL,
    reading_value NUMERIC(12, 3) NOT NULL,
    source        VARCHAR(255) NOT NULL,
    recorded_by   BIGINT,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_water_usage_readings_meter_date UNIQUE (meter_id, reading_date),
    CONSTRAINT fk_water_usage_readings_meter FOREIGN KEY (meter_id) REFERENCES water_meters (id),
    CONSTRAINT fk_water_usage_readings_recorded_by FOREIGN KEY (recorded_by) REFERENCES community_admins (id)
);

ALTER TABLE residents ADD COLUMN household_id BIGINT REFERENCES households (id);
