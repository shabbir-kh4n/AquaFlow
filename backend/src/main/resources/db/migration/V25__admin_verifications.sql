CREATE TABLE admin_verifications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id          BIGINT NOT NULL,
    document_type     VARCHAR(60) NOT NULL,
    document_number   VARCHAR(100) NOT NULL,
    details           TEXT,
    file_name         VARCHAR(255) NOT NULL,
    file_size         BIGINT NOT NULL,
    file_data         BYTEA NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    rejection_reason  TEXT,
    submitted_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reviewed_at       TIMESTAMP(6) WITH TIME ZONE,
    -- One row per admin (a resubmission after rejection overwrites it). No ON DELETE CASCADE, same
    -- convention as support_tickets/announcements: SystemAdminService.deleteCommunityAdmin deletes it explicitly.
    CONSTRAINT uk_admin_verifications_admin UNIQUE (admin_id),
    CONSTRAINT fk_admin_verifications_admin FOREIGN KEY (admin_id) REFERENCES community_admins (id),
    CONSTRAINT chk_admin_verifications_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);
