ALTER TABLE invoices
    ADD COLUMN tariff_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    ADD COLUMN common_area_amount NUMERIC(12, 2) NOT NULL DEFAULT 0;

-- Every existing invoice's total_amount was tariff-only before this change.
UPDATE invoices SET tariff_amount = total_amount WHERE tariff_amount = 0;

CREATE TABLE invoice_common_area_charges (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id          BIGINT NOT NULL,
    cost_item_id        BIGINT,
    label               VARCHAR(255) NOT NULL,
    amount              NUMERIC(12, 2) NOT NULL,
    distribution_method VARCHAR(20) NOT NULL,
    CONSTRAINT fk_invoice_common_area_charges_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE
);
