-- One-time "forgot password" tokens for every account type. Only the SHA-256 hash of the emailed token
-- is stored. No FK on account_id (it points at one of three tables depending on account_type), so
-- deleting an account never has to touch this table; a stale token just fails to resolve its account.
CREATE TABLE password_reset_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash    VARCHAR(64) NOT NULL,
    account_type  VARCHAR(20) NOT NULL,
    account_id    BIGINT NOT NULL,
    expires_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_password_reset_tokens_hash UNIQUE (token_hash),
    CONSTRAINT chk_password_reset_tokens_type CHECK (account_type IN ('ADMIN', 'RESIDENT', 'SYSTEM_ADMIN'))
);

CREATE INDEX idx_password_reset_tokens_account ON password_reset_tokens (account_type, account_id);
