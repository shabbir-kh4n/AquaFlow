CREATE TABLE support_tickets (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id         BIGINT NOT NULL,
    raised_by_role       VARCHAR(20) NOT NULL,
    resident_id          BIGINT,
    community_admin_id   BIGINT,
    subject              VARCHAR(200) NOT NULL,
    status               VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    resolved_at          TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_support_tickets_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id),
    CONSTRAINT fk_support_tickets_resident FOREIGN KEY (resident_id) REFERENCES residents (id),
    CONSTRAINT fk_support_tickets_admin FOREIGN KEY (community_admin_id) REFERENCES community_admins (id),
    CONSTRAINT chk_support_tickets_raiser CHECK (
        (raised_by_role = 'RESIDENT' AND resident_id IS NOT NULL AND community_admin_id IS NULL) OR
        (raised_by_role = 'ADMIN' AND community_admin_id IS NOT NULL AND resident_id IS NULL)
    )
);

CREATE INDEX idx_support_tickets_apartment ON support_tickets (apartment_id);
CREATE INDEX idx_support_tickets_resident ON support_tickets (resident_id);
CREATE INDEX idx_support_tickets_admin ON support_tickets (community_admin_id);

CREATE TABLE support_ticket_messages (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     BIGINT NOT NULL,
    sender_role   VARCHAR(20) NOT NULL,
    sender_name   VARCHAR(150) NOT NULL,
    message       VARCHAR(2000) NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_support_ticket_messages_ticket FOREIGN KEY (ticket_id) REFERENCES support_tickets (id) ON DELETE CASCADE
);

CREATE INDEX idx_support_ticket_messages_ticket ON support_ticket_messages (ticket_id);
