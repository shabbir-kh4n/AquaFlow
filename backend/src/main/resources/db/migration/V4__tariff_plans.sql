CREATE TABLE tariff_plans (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id BIGINT NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_tariff_plans_apartment_id UNIQUE (apartment_id),
    CONSTRAINT fk_tariff_plans_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id)
);

CREATE TABLE tariff_tiers (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tariff_plan_id BIGINT NOT NULL,
    tier_order     INT NOT NULL,
    min_units      NUMERIC(12, 3) NOT NULL,
    max_units      NUMERIC(12, 3),
    rate_per_unit  NUMERIC(10, 2) NOT NULL,
    CONSTRAINT uk_tariff_tiers_plan_order UNIQUE (tariff_plan_id, tier_order),
    CONSTRAINT fk_tariff_tiers_plan FOREIGN KEY (tariff_plan_id) REFERENCES tariff_plans (id) ON DELETE CASCADE
);
