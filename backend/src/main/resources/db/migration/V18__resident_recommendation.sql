CREATE TABLE resident_recommendations (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resident_id           BIGINT NOT NULL UNIQUE,
    tips                  TEXT NOT NULL,
    generated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    source_period_month   VARCHAR(7),
    CONSTRAINT fk_resident_recommendations_resident FOREIGN KEY (resident_id) REFERENCES residents (id) ON DELETE CASCADE
);
