CREATE TABLE bulk_water_purchases (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id   BIGINT NOT NULL,
    purchase_date  DATE NOT NULL,
    source         VARCHAR(255) NOT NULL,
    volume_liters  NUMERIC(12, 2) NOT NULL,
    unit_cost      NUMERIC(10, 4) NOT NULL,
    total_cost     NUMERIC(12, 2) NOT NULL,
    notes          VARCHAR(500),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_bulk_water_purchases_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id)
);

CREATE INDEX idx_bulk_water_purchases_apartment_date ON bulk_water_purchases (apartment_id, purchase_date DESC);
