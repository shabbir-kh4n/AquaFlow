CREATE TABLE alert_configs (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id                BIGINT NOT NULL UNIQUE,
    monthly_threshold_kl        NUMERIC(12, 3),
    outlier_std_dev_multiplier  NUMERIC(6, 2) NOT NULL DEFAULT 2.0,
    threshold_alerts_enabled    BOOLEAN NOT NULL DEFAULT TRUE,
    outlier_alerts_enabled      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at                  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at                  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_alert_configs_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id)
);

CREATE TABLE alerts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id        BIGINT NOT NULL,
    apartment_id        BIGINT NOT NULL,
    alert_type          VARCHAR(30) NOT NULL,
    period_month        VARCHAR(7) NOT NULL,
    consumption_value   NUMERIC(12, 3) NOT NULL,
    reference_value     NUMERIC(12, 3) NOT NULL,
    message             VARCHAR(500) NOT NULL,
    status              VARCHAR(20) NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    resolved_at         TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_alerts_household_period_type UNIQUE (household_id, period_month, alert_type),
    CONSTRAINT fk_alerts_household FOREIGN KEY (household_id) REFERENCES households (id) ON DELETE CASCADE,
    CONSTRAINT fk_alerts_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id)
);
