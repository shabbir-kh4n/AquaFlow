-- Baseline migration recreating the schema Hibernate (ddl-auto=update) had already produced
-- for community_admins, residents, and password_setup_tokens before Flyway was introduced.
-- Verified against the live local Postgres instance via `\d+` on 2026-08-31.

CREATE TABLE community_admins (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    email       VARCHAR(255) NOT NULL,
    full_name   VARCHAR(255) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    phone       VARCHAR(255),
    unit_number VARCHAR(255),
    CONSTRAINT uk_community_admins_email UNIQUE (email)
);

CREATE TABLE residents (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date_of_birth    VARCHAR(255),
    email            VARCHAR(255) NOT NULL,
    full_name        VARCHAR(255) NOT NULL,
    gender           VARCHAR(255),
    government_id    VARCHAR(255),
    house_number     VARCHAR(255) NOT NULL,
    meter_number     VARCHAR(255),
    phone            VARCHAR(255),
    admin_id         BIGINT NOT NULL,
    date_of_joining  VARCHAR(255),
    password         VARCHAR(255),
    password_set     BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_residents_admin FOREIGN KEY (admin_id) REFERENCES community_admins (id)
);

CREATE TABLE password_setup_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    token       VARCHAR(255) NOT NULL,
    used        BOOLEAN NOT NULL,
    resident_id BIGINT NOT NULL,
    CONSTRAINT uk_password_setup_tokens_token UNIQUE (token),
    CONSTRAINT fk_password_setup_tokens_resident FOREIGN KEY (resident_id) REFERENCES residents (id)
);
