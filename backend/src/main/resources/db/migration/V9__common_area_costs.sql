CREATE TABLE common_area_configs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id         BIGINT NOT NULL,
    distribution_method  VARCHAR(20) NOT NULL DEFAULT 'CONSUMPTION',
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_common_area_configs_apartment_id UNIQUE (apartment_id),
    CONSTRAINT fk_common_area_configs_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id)
);

CREATE TABLE common_area_cost_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id      BIGINT NOT NULL,
    label          VARCHAR(255) NOT NULL,
    monthly_amount NUMERIC(12, 2) NOT NULL,
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_common_area_cost_items_config FOREIGN KEY (config_id) REFERENCES common_area_configs (id) ON DELETE CASCADE
);
