CREATE TABLE billing_cycles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartment_id  BIGINT NOT NULL,
    period_month  VARCHAR(7) NOT NULL,
    status        VARCHAR(20) NOT NULL,
    opened_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finalized_at  TIMESTAMP(6) WITH TIME ZONE,
    archived_at   TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_billing_cycles_apartment_period UNIQUE (apartment_id, period_month),
    CONSTRAINT fk_billing_cycles_apartment FOREIGN KEY (apartment_id) REFERENCES apartments (id)
);

CREATE TABLE invoices (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_cycle_id    BIGINT NOT NULL,
    household_id        BIGINT NOT NULL,
    consumption_units   NUMERIC(12, 3) NOT NULL,
    total_amount        NUMERIC(12, 2) NOT NULL,
    generated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_invoices_cycle_household UNIQUE (billing_cycle_id, household_id),
    CONSTRAINT fk_invoices_billing_cycle FOREIGN KEY (billing_cycle_id) REFERENCES billing_cycles (id) ON DELETE CASCADE,
    CONSTRAINT fk_invoices_household FOREIGN KEY (household_id) REFERENCES households (id)
);

CREATE TABLE invoice_line_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id     BIGINT NOT NULL,
    tier_order     INT NOT NULL,
    units_in_tier  NUMERIC(12, 3) NOT NULL,
    rate_per_unit  NUMERIC(10, 2) NOT NULL,
    amount         NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_invoice_line_items_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE
);
