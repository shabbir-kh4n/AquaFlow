CREATE TABLE system_metric_samples (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    captured_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ops_per_second      DOUBLE PRECISION NOT NULL,
    avg_latency_ms      DOUBLE PRECISION NOT NULL,
    read_latency_ms     DOUBLE PRECISION NOT NULL,
    write_latency_ms    DOUBLE PRECISION NOT NULL,
    other_latency_ms    DOUBLE PRECISION NOT NULL,
    active_connections  INTEGER NOT NULL,
    total_keys          INTEGER NOT NULL
);

CREATE INDEX idx_system_metric_samples_captured_at ON system_metric_samples (captured_at);
